"""Refresh the static latest-study link from the dated published archive cards."""
import argparse
from datetime import date
from html import escape
from html.parser import HTMLParser
from pathlib import Path
import re

START = '<!-- Latest study: generated by scripts/update_collection.py -->'
END = '<!-- End latest study -->'
ROUTE = re.compile(r'(?:lessons/)?[a-z0-9-]+\.html\Z')


class CollectionCards(HTMLParser):
    def __init__(self, html):
        super().__init__()
        self.cards = []
        self.card = None
        self.capture = False
        self.feed(html)
        if not self.cards:
            raise ValueError('No dated archive cards found')

    def handle_starttag(self, tag, pairs):
        attrs = dict(pairs)
        if tag == 'li' and 'data-week-start' in attrs:
            self.card = {
                'date': date.fromisoformat(attrs['data-week-start']),
                'ready': False,
                'route': None,
                'title': '',
            }
        if self.card is None:
            return
        if tag == 'span' and {'status', 'ready'} <= set(attrs.get('class', '').split()):
            self.card['ready'] = True
        if tag == 'a' and self.card['route'] is None:
            self.card['route'] = attrs.get('href')
            self.capture = True

    def handle_endtag(self, tag):
        if tag == 'a':
            self.capture = False
        if tag == 'li' and self.card is not None:
            if not ROUTE.fullmatch(self.card['route'] or '') or not self.card['title'].strip():
                raise ValueError('Each dated archive card needs a local study title link')
            self.cards.append(self.card)
            self.card = None

    def handle_data(self, text):
        if self.capture and self.card is not None:
            self.card['title'] += text


def render(html):
    if html.count(START) != 1 or html.count(END) != 1:
        raise ValueError('Expected one generated latest-study slot')
    start, _, after = html.partition(START)
    _, _, end = after.partition(END)
    cards = CollectionCards(html).cards
    if len({card['date'] for card in cards}) != len(cards):
        raise ValueError('Archive card dates must be unique')
    ready = [card for card in cards if card['ready']]
    output = ''
    if ready:
        latest = max(ready, key=lambda card: card['date'])
        title = escape(latest['title'].strip())
        route = escape(latest['route'], quote=True)
        output = (
            '<div class="latest-study"><p class="latest-study-title">'
            f'<span>Latest published study</span><strong>{title}</strong></p>'
            f'<a class="button latest-study-link" href="{route}">Open the latest study</a></div>\n'
        )
    return f'{start}{START}\n{output}{END}{end}'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if the tracked HTML needs regenerating')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    aliases = (root / 'index.html', root / 'lessons.html')
    canonical = render(aliases[0].read_text(encoding='utf-8'))
    mismatches = [path for path in aliases if path.read_text(encoding='utf-8') != canonical]
    if args.check and mismatches:
        parser.exit(1, 'Collection is stale. Run python scripts/update_collection.py.\n')
    for path in mismatches:
        path.write_text(canonical, encoding='utf-8')


if __name__ == '__main__':
    main()
